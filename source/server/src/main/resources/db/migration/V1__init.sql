-- Caro Online - initial schema.
-- Written in portable SQL so it runs on PostgreSQL (prod) and H2 in PostgreSQL mode (tests).

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(20)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    display_name  VARCHAR(30)  NOT NULL,
    role          VARCHAR(10)  NOT NULL DEFAULT 'PLAYER',
    status        VARCHAR(10)  NOT NULL DEFAULT 'ACTIVE',
    rating        INT          NOT NULL DEFAULT 1000,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_users_role   CHECK (role IN ('PLAYER', 'ADMIN')),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'LOCKED'))
);

-- One row per finished match. The primary key is the in-memory match id,
-- so a match can never be stored twice.
CREATE TABLE matches (
    id              UUID PRIMARY KEY,
    room_id         VARCHAR(20)  NOT NULL,
    player_x_id     BIGINT       NOT NULL REFERENCES users (id),
    player_o_id     BIGINT       NOT NULL REFERENCES users (id),
    winner_id       BIGINT       REFERENCES users (id),
    result          VARCHAR(10)  NOT NULL,
    end_reason      VARCHAR(20)  NOT NULL,
    rating_change_x INT          NOT NULL DEFAULT 0,
    rating_change_o INT          NOT NULL DEFAULT 0,
    total_moves     INT          NOT NULL,
    started_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_matches_result CHECK (result IN ('X_WIN', 'O_WIN', 'DRAW', 'ABORTED')),
    CONSTRAINT ck_matches_reason CHECK (end_reason IN
        ('FIVE_IN_ROW', 'BOARD_FULL', 'RESIGN', 'TIMEOUT', 'DISCONNECT', 'BOTH_DISCONNECTED'))
);

CREATE INDEX idx_matches_player_x ON matches (player_x_id, ended_at);
CREATE INDEX idx_matches_player_o ON matches (player_o_id, ended_at);
CREATE INDEX idx_matches_ended_at ON matches (ended_at);

CREATE TABLE match_moves (
    match_id  UUID     NOT NULL REFERENCES matches (id) ON DELETE CASCADE,
    move_no   INT      NOT NULL,
    player_id BIGINT   NOT NULL REFERENCES users (id),
    x         INT      NOT NULL,
    y         INT      NOT NULL,
    played_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (match_id, move_no)
);
